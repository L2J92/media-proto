-- V1: 초기 스키마 (Hibernate ddl-auto 로 운영되던 스키마를 그대로 옮김)
-- 운영 DB는 이미 이 스키마가 있으므로 baseline(1)로 기록만 하고 이 파일은 실행하지 않는다.

create table users (
    id            bigint generated by default as identity primary key,
    email         varchar(100)                not null unique,
    password_hash varchar(255)                not null,
    nickname      varchar(30)                 not null,
    created_at    timestamp(6) with time zone not null,
    updated_at    timestamp(6) with time zone not null
);

create table broadcasts (
    id                      bigint generated by default as identity primary key,
    owner_id                bigint                      not null references users (id),
    title                   varchar(100)                not null,
    description             varchar(1000),
    status                  varchar(10)                 not null,
    room_name               varchar(64),
    source                  varchar(10),
    started_at              timestamp(6) with time zone,
    ended_at                timestamp(6) with time zone,
    publisher_absent_since  timestamp(6) with time zone,
    room_closed             boolean                     not null,
    deleted_at              timestamp(6) with time zone,
    version                 bigint,
    created_at              timestamp(6) with time zone not null,
    updated_at              timestamp(6) with time zone not null
);
create index idx_broadcast_status on broadcasts (status);
create unique index idx_broadcast_room on broadcasts (room_name);

create table chat_messages (
    id           bigint generated by default as identity primary key,
    broadcast_id bigint                      not null references broadcasts (id),
    author_id    bigint                      not null references users (id),
    content      varchar(300)                not null,
    edited       boolean                     not null,
    deleted_at   timestamp(6) with time zone,
    created_at   timestamp(6) with time zone not null,
    updated_at   timestamp(6) with time zone not null
);
create index idx_chat_broadcast on chat_messages (broadcast_id, id);

create table recordings (
    id              bigint generated by default as identity primary key,
    broadcast_id    bigint                      not null references broadcasts (id),
    egress_id       varchar(64)                 not null,
    file_path       varchar(300)                not null,
    location        varchar(500),
    duration_millis bigint,
    status          varchar(10)                 not null,
    created_at      timestamp(6) with time zone not null,
    updated_at      timestamp(6) with time zone not null
);
create unique index idx_recording_egress on recordings (egress_id);

create table wallets (
    id         bigint generated by default as identity primary key,
    user_id    bigint                      not null,
    balance    bigint                      not null,
    version    bigint,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null
);
create unique index uk_wallet_user on wallets (user_id);

create table point_transactions (
    id            bigint generated by default as identity primary key,
    user_id       bigint                      not null,
    type          varchar(20)                 not null,
    amount        bigint                      not null,
    balance_after bigint                      not null,
    ref_id        bigint,
    description   varchar(100),
    created_at    timestamp(6) with time zone not null,
    updated_at    timestamp(6) with time zone not null
);
create index idx_point_tx_user on point_transactions (user_id, id);

create table charge_orders (
    id                    bigint generated by default as identity primary key,
    user_id               bigint                      not null,
    amount                bigint                      not null,
    order_id              varchar(64)                 not null,
    customer_key          varchar(64)                 not null,
    donation_broadcast_id bigint,
    donation_message      varchar(100),
    payment_key           varchar(200),
    status                varchar(10)                 not null,
    fail_reason           varchar(200),
    approved_at           timestamp(6) with time zone,
    version               bigint,
    created_at            timestamp(6) with time zone not null,
    updated_at            timestamp(6) with time zone not null
);
create unique index uk_charge_order on charge_orders (order_id);
create unique index uk_charge_payment on charge_orders (payment_key);

create table point_donations (
    id              bigint generated by default as identity primary key,
    broadcast_id    bigint                      not null references broadcasts (id),
    streamer_id     bigint                      not null references users (id),
    donor_id        bigint                      not null references users (id),
    amount          bigint                      not null,
    message         varchar(100),
    request_id      varchar(64)                 not null,
    charge_order_id bigint,
    created_at      timestamp(6) with time zone not null,
    updated_at      timestamp(6) with time zone not null
);
create unique index uk_donation_request on point_donations (request_id);
create unique index uk_donation_charge on point_donations (charge_order_id);
create index idx_donation_broadcast on point_donations (broadcast_id, id);

-- Spring Session JDBC (로그인 세션 저장)
create table spring_session (
    primary_id            char(36)     not null,
    session_id            char(36)     not null,
    creation_time         bigint       not null,
    last_access_time      bigint       not null,
    max_inactive_interval int          not null,
    expiry_time           bigint       not null,
    principal_name        varchar(100),
    constraint spring_session_pk primary key (primary_id)
);
create unique index spring_session_ix1 on spring_session (session_id);
create index spring_session_ix2 on spring_session (expiry_time);
create index spring_session_ix3 on spring_session (principal_name);

create table spring_session_attributes (
    session_primary_id char(36)     not null,
    attribute_name     varchar(200) not null,
    attribute_bytes    bytea        not null,
    constraint spring_session_attributes_pk primary key (session_primary_id, attribute_name),
    constraint spring_session_attributes_fk foreign key (session_primary_id)
        references spring_session (primary_id) on delete cascade
);

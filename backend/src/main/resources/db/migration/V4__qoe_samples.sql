-- V4: 시청 품질(QoE) 샘플. 시청자 플레이어가 10초마다 WebRTC 통계를 보낸다.
create table qoe_samples (
    id              bigint generated by default as identity primary key,
    broadcast_id    bigint                      not null references broadcasts (id),
    viewer_key      varchar(64)                 not null,
    bitrate_kbps    integer                     not null,
    packet_loss_pct double precision            not null,
    jitter_ms       double precision            not null,
    rtt_ms          double precision            not null,
    fps             double precision            not null,
    frames_dropped  integer                     not null,
    freeze_count    integer                     not null,
    frame_height    integer                     not null,
    quality         varchar(10)                 not null,
    created_at      timestamp(6) with time zone not null
);
create index idx_qoe_broadcast_time on qoe_samples (broadcast_id, created_at);

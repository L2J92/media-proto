-- V5: 스트리머 채널과 팔로우
create table channels (
    id          bigint generated by default as identity primary key,
    owner_id    bigint                      not null unique references users (id),
    handle      varchar(30)                 not null,
    name        varchar(50)                 not null,
    description varchar(500),
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null
);
create unique index uk_channel_handle on channels (handle);

create table follows (
    id         bigint generated by default as identity primary key,
    user_id    bigint                      not null references users (id),
    channel_id bigint                      not null references channels (id),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null
);
create unique index uk_follow_user_channel on follows (user_id, channel_id);
create index idx_follow_channel on follows (channel_id);

-- 기존 회원에게 기본 채널(@u{회원ID}, 이름=닉네임)을 만들어 준다
insert into channels (owner_id, handle, name, created_at, updated_at)
select u.id, 'u' || u.id, u.nickname, current_timestamp, current_timestamp
from users u
where not exists (select 1 from channels c where c.owner_id = u.id);

-- V6: 채팅 관리 (매니저, 채팅 금지/차단, 슬로우 모드)
alter table channels add column slow_mode_seconds integer default 0 not null;

create table channel_managers (
    id         bigint generated by default as identity primary key,
    channel_id bigint                      not null references channels (id),
    user_id    bigint                      not null references users (id),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null
);
create unique index uk_channel_manager on channel_managers (channel_id, user_id);

create table channel_bans (
    id          bigint generated by default as identity primary key,
    channel_id  bigint                      not null references channels (id),
    user_id     bigint                      not null references users (id),
    -- null 이면 영구 차단, 값이 있으면 그 시각까지 채팅 금지
    until       timestamp(6) with time zone,
    reason      varchar(100),
    created_by  bigint                      not null,
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null
);
create unique index uk_channel_ban on channel_bans (channel_id, user_id);
